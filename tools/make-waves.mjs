#!/usr/bin/env node
// Write src/waves.js: the outline of each alfaia sample (peak level per slice, 0 to 1) and its
// length, which the baque scenes draw as the sound wave. Run it again after an alfaia WAV
// changes. Reads the 16-bit PCM WAV masters in sounds/; needs nothing else.
// Usage: node tools/make-waves.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOUNDS = path.join(ROOT, 'sounds');
// RIFF layout (https://www.mmsp.ece.mcgill.ca/Documents/AudioFormats/WAVE/WAVE.html)
const RIFF_HEADER = 12; // bytes before the first chunk
const CHUNK_ID = 4; // bytes of a chunk's id; its size follows
const CHUNK_HEADER = 8; // id and size
const FMT_CHANNELS = 2; // offsets inside the fmt chunk
const FMT_RATE = 4;
const FMT_BITS = 14;
const PCM_BITS = 16;
const BYTES_PER_SAMPLE = 2; // 16-bit PCM
const INT16_SCALE = 32768;
const MS_PER_SECOND = 1000;
const SLICES = 56; // bars per wave: enough detail at phone width, small in the bundle
const LEVEL_STEPS = 100; // levels are stored as whole percents

/** Samples (−1 to 1) and rate of a mono or stereo 16-bit PCM WAV; stereo is read as its left channel. */
function readWav(file) {
  const data = readFileSync(file);
  let offset = RIFF_HEADER,
    channels = 1,
    rate = 0;
  while (offset < data.length) {
    const id = data.toString('ascii', offset, offset + CHUNK_ID),
      size = data.readUInt32LE(offset + CHUNK_ID),
      body = offset + CHUNK_HEADER;
    if (id === 'fmt ') {
      if (data.readUInt16LE(body + FMT_BITS) !== PCM_BITS) throw new Error(`${file}: not 16-bit PCM`);
      channels = data.readUInt16LE(body + FMT_CHANNELS);
      rate = data.readUInt32LE(body + FMT_RATE);
    }
    if (id === 'data') {
      const frames = size / (BYTES_PER_SAMPLE * channels),
        samples = new Float32Array(frames);
      for (let i = 0; i < frames; i++) samples[i] = data.readInt16LE(body + i * BYTES_PER_SAMPLE * channels) / INT16_SCALE;
      return { samples, rate };
    }
    offset = body + size + (size % 2);
  }
  throw new Error(`${file}: no data chunk`);
}

const waves = {};
for (const name of readdirSync(SOUNDS)
  .filter(file => /^alfaia-.+-(main|answer)\.wav$/.test(file))
  .map(file => file.slice(0, -'.wav'.length))
  .sort()) {
  const { samples, rate } = readWav(path.join(SOUNDS, `${name}.wav`));
  const peaks = [];
  for (let slice = 0; slice < SLICES; slice++) {
    let peak = 0;
    for (let i = Math.floor((slice * samples.length) / SLICES); i < Math.floor(((slice + 1) * samples.length) / SLICES); i++)
      peak = Math.max(peak, Math.abs(samples[i]));
    peaks.push(peak);
  }
  const top = Math.max(...peaks) || 1;
  waves[name] = { ms: Math.round((samples.length / rate) * MS_PER_SECOND), peaks: peaks.map(peak => Math.round((peak / top) * LEVEL_STEPS)) };
}

const lines = Object.entries(waves).map(([name, wave]) => `  '${name}': { ms: ${wave.ms}, peaks: [${wave.peaks.join(', ')}] },`);
writeFileSync(
  path.join(ROOT, 'src', 'waves.js'),
  `// Generated by tools/make-waves.mjs from the alfaia WAV masters: do not edit by hand.\n// Each wave: the sample length in ms and its peak level per slice, in percent of its loudest slice.\nexport const WAVES = {\n${lines.join('\n')}\n};\n`,
);
console.log(`make-waves: ${lines.length} waves written`);
